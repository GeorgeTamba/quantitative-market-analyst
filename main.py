@app.get("/api/chart/{ticker}")
def get_chart_data(ticker: str, timeframe: str = "1D"):
    """
    Fetches raw OHLCV candlestick data for the TradingView frontend chart.
    Timeframes now represent the CANDLE SIZE (TradingView style).
    """
    try:
        symbol = _normalize_ticker(ticker)
        timeframe = timeframe.upper()
        
        # 1. Map frontend buttons to Yahoo Finance intervals (Candle Size)
        if timeframe == "15M":
            period = "5d"       # 5 days total of 15-minute candles
            interval = "15m"
        elif timeframe == "1H":
            period = "1mo"      # 1 month total of 1-hour candles
            interval = "1h"
        elif timeframe == "1D":
            period = "2y"       # 2 years total of 1-day candles
            interval = "1d"
        elif timeframe == "1W":
            period = "5y"       # 5 years total of 1-week candles
            interval = "1wk"
        else:
            period = "2y"
            interval = "1d"
            
        # 2. Fetch the data
        tk = yf.Ticker(symbol)
        df = tk.history(period=period, interval=interval)
        
        # ... (the rest of the function stays exactly the same!) ...
        
        if df.empty:
            raise HTTPException(status_code=404, detail=f"No chart data found for {symbol}")
            
        # 3. Format the data EXACTLY how TradingView Lightweight Charts expects it
        chart_data = []
        for index, row in df.iterrows():
            # Lightweight charts requires UNIX timestamps in exact SECONDS (not milliseconds)
            timestamp_seconds = int(index.timestamp())
            
            chart_data.append({
                "time": timestamp_seconds, 
                "open": round(row["Open"], 2),
                "high": round(row["High"], 2),
                "low": round(row["Low"], 2),
                "close": round(row["Close"], 2),
                "value": round(row["Volume"], 2) # Adding volume in case you want a volume bar chart later
            })
            
        return {
            "ticker": symbol, 
            "timeframe": timeframe,
            "data": chart_data
        }
        
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

